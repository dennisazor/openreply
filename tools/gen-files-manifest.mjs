#!/usr/bin/env node
/**
 * Generates lib/files-manifest.ts from whatever is in public/.
 *
 * Why a build-time manifest instead of reading public/ at request time:
 * on Vercel, public/ is uploaded to the CDN as static assets and is NOT
 * guaranteed to exist inside the serverless function bundle, so fs.readdir
 * at request time can return nothing. Files only change via a git push
 * (which triggers a rebuild), so a build-time snapshot is always accurate.
 *
 * Runs automatically as part of `npm run build` and `npm run vercel-build`.
 */

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const PUBLIC_DIR = path.join(ROOT, "public");
const OUT = path.join(ROOT, "lib", "files-manifest.ts");

// Next.js starter artwork - noise on a lead-magnet page.
const IGNORE = new Set([
  "file.svg", "globe.svg", "next.svg", "vercel.svg", "window.svg",
  ".DS_Store", "favicon.ico", "robots.txt", "sitemap.xml",
]);

let entries = [];
if (fs.existsSync(PUBLIC_DIR)) {
  entries = fs
    .readdirSync(PUBLIC_DIR, { withFileTypes: true })
    .filter((d) => d.isFile() && !d.name.startsWith(".") && !IGNORE.has(d.name))
    .map((d) => {
      const { size, mtime } = fs.statSync(path.join(PUBLIC_DIR, d.name));
      return {
        name: d.name,
        urlPath: "/" + d.name,
        bytes: size,
        ext: path.extname(d.name).slice(1).toLowerCase(),
        modified: mtime.toISOString(),
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

const banner = `// AUTO-GENERATED by tools/gen-files-manifest.mjs - do not edit by hand.
// Regenerate with: npm run files:manifest
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  banner +
    `
export interface PublicFile {
  name: string;
  urlPath: string;
  bytes: number;
  ext: string;
  modified: string;
}

export const generatedAt = ${JSON.stringify(new Date().toISOString())};

export const publicFiles: PublicFile[] = ${JSON.stringify(entries, null, 2)};
`,
  "utf8"
);

console.log(`[files-manifest] ${entries.length} file(s) -> lib/files-manifest.ts`);
